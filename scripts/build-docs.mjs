/* ── Search index ─────────────────────────────────────────────────────────
   One entry per heading, so a result lands on the right part of a page rather
   than at its top. Built from the raw Markdown — stripping the markup before
   splitting would remove the '#' the split depends on, which quietly collapsed
   every page down to a single entry the first time. */
const stripMarkdown = (text) => text
	.replace(/```[\s\S]*?```/g, ' ')          // fenced code
	.replace(/`([^`]*)`/g, '$1')              // inline code
	.replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1') // links and images
	.replace(/[*_>|]/g, ' ')
	.replace(/\s+/g, ' ')
	.trim();


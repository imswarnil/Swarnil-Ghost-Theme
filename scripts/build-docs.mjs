const icon = (name, cls = 'icon') =>
	`<svg class="${cls}" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${ICONS[name] || ''}</svg>`;

const escapeHtml = (text) =>
	String(text).replace(/[&<>"]/g, (c) =>
		({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);

const slugify = (text) =>
	text.toLowerCase().replace(/[^\w\s-]/g, '').trim().replace(/\s+/g, '-');

/* ── Read the sources ─────────────────────────────────────────────────── */

const parse = (source, file) => {
	const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
	if (!match) throw new Error(`${file}: missing front matter`);
	const meta = {};
	for (const line of match[1].split('\n')) {
		const pair = line.match(/^(\w+):\s*(.*)$/);
		if (pair) meta[pair[1]] = /^\d+$/.test(pair[2].trim()) ? Number(pair[2]) : pair[2].trim();
	}
	return { meta, body: match[2] };
};

const files = (await readdir(SRC)).filter((f) => f.endsWith('.md')).sort();

const pages = [];
for (const file of files) {
	const { meta, body } = parse(await readFile(join(SRC, file), 'utf8'), file);
	const headings = [];

	// Render once, collecting h2/h3 for the contents rail and giving every
	// heading a stable id and a hover anchor.
	const html = marked.parse(body).replace(
		/<h([23])>([\s\S]*?)<\/h\1>/g,
		(_, level, inner) => {
			const plain = inner.replace(/<[^>]+>/g, '');
			const id = slugify(plain);
			headings.push({ id, text: plain, level: Number(level) });
			return `<h${level} id="${id}">${inner}<a class="anchor" href="#${id}" aria-label="Link to this section">#</a></h${level}>`;
		},
	);

	pages.push({ ...meta, html, headings, raw: body });
}

pages.sort((a, b) => a.order - b.order);

/* Groups, in the order they first appear — the front matter decides the
   structure, so adding a section never means editing this file. */
const groups = [];
for (const page of pages) {
	let group = groups.find((g) => g.name === page.group);
	if (!group) groups.push((group = { name: page.group, pages: [] }));
	group.pages.push(page);
}


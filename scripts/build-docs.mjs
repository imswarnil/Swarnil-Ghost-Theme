/*
 * Builds the documentation site.
 *
 *   docs/src/*.md  →  docs/index.html
 *                     docs/<slug>/index.html   (one page per section)
 *                     docs/print.html          (all sections, for the PDF)
 *                     docs/search-index.json
 *                     docs/assets/thumb-*.svg
 *
 * Multipage rather than one long scroll: each section is a URL someone can
 * link to and land on, which is what documentation is for. The single-page
 * version still exists as print.html, because a PDF wants one continuous
 * document and a reader offline wants all of it.
 *
 * docs/assets/docs.css and docs/assets/docs.js are hand-authored and are not
 * generated by this script — it only writes HTML, the search index and the
 * section artwork.
 *
 * The site is published at theme.imswarnil.com/docs/. GitHub Pages serves the
 * repository root, so this folder — docs/ — lands at /docs/ without any path
 * rewriting, and CNAME and .nojekyll are written to the repository root rather
 * than in here. Every internal link and asset href is built from BASE below.
 *
 * print.html is the exception to all of it: the PDF step opens it as a local
 * file, so its CSS is inlined and it links to nothing.
 *
 *   npm run docs
 */

import { readdir, readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
